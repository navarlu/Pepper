"""Inline gesture tags: catalog, prompt section, and stream parser.

The embodiment layer prototyped in docs/paper/benchmark (MOVE_BODY_MODE
= "inline"), ported to the LiveKit streaming agent. The LLM starts every
sentence with an animation tag like `[Hey_1]`; `InlineGestureParser`
filters the streamed LLM text inside `llm_node`, fires each resolved tag
as a robot gesture, and strips it so the TTS never speaks it.

Data source is `src/experiment/data/animation_catalog.json`, a bundle of
the Gemini annotations generated by
`experiments/animation_metadata/build_agent_catalog.py` — regenerate and
redeploy after re-annotating. Every bundle name is verified to resolve
through `robot/data/animations.json`.
"""

from __future__ import annotations

import difflib
import json
import re
from pathlib import Path

from ._events import emit_experiment_event

_CATALOG_FILE = Path(__file__).resolve().parents[2] / "data" / "animation_catalog.json"


def _tidy_caption(caption: str) -> str:
    """'The robot raises its left hand.' -> 'raises its left hand'."""
    c = (caption or "").strip()
    if c.startswith("The robot "):
        c = c[len("The robot "):]
    return c.rstrip(".")


def _load_entries() -> dict[str, dict]:
    raw = json.loads(_CATALOG_FILE.read_text(encoding="utf-8"))
    entries = {e["name"]: e for e in raw}
    if not entries:
        raise RuntimeError(f"inline gestures: empty catalog {_CATALOG_FILE}")
    return entries


_ENTRIES = _load_entries()
_NAME_BY_LOWER = {name.lower(): name for name in _ENTRIES}

print(f"[gest] catalog loaded animations={len(_ENTRIES)} file={_CATALOG_FILE}")

CATALOG_TEXT = "\n".join(
    f"{name}: {_tidy_caption(e['caption'])} | {', '.join(e['functions'])} | "
    f"{', '.join(e['tone'])} | {e['energy']}"
    for name, e in sorted(_ENTRIES.items())
)

# Appended to SYSTEM_PROMPT when ENABLE_INLINE_GESTURES is on. Kept
# byte-stable (sorted catalog, static text) so the prompt prefix caches.
# The example uses real catalog names — showing the pattern beats
# describing it, and per-sentence tagging needs the mechanical
# "start every sentence" rule to hold on small models.
INLINE_GESTURES_PROMPT_SECTION = f"""

# Speaking style (embodied)

Speak in short, simple sentences. Put one idea in each sentence and end \
it with a period — where you would chain clauses with a comma, start a \
new sentence instead. Use at most three sentences per answer.

# Body movement

You have a physical robot body and you always move while you speak. \
Start every sentence with an animation tag — an animation name in square \
brackets. Pick the animation whose movement, communicative functions and \
tone best match what that sentence says: greeting, saying goodbye, \
apologizing, agreeing, declining, explaining, pointing, waiting, or \
reacting emotionally. Use only names exactly as they appear in the list \
below.

Reply format example (every sentence starts with its own tag):
[Hey_1] Hi there. [Explain_3] The canteen is on the ground floor. [BowShort_1] Enjoy your visit.

Available animations (Name: movement | communicative functions | tone | energy):
{CATALOG_TEXT}
"""


def resolve_gesture(raw: str) -> tuple[str | None, list[str]]:
    """Resolve a model-written tag to a canonical catalog name.

    Returns (name, suggestions); name is None when unresolved, with the
    closest catalog names as suggestions for the log.
    """
    key = (raw or "").strip().strip("'\"").lower()
    if key in _NAME_BY_LOWER:
        return _NAME_BY_LOWER[key], []
    close = difflib.get_close_matches(key, _NAME_BY_LOWER.keys(), n=3, cutoff=0.6)
    return None, [_NAME_BY_LOWER[c] for c in close]


def gesture_has_sound(name: str) -> bool:
    entry = _ENTRIES.get(name)
    return bool(entry and entry.get("has_sound"))


# A tag candidate is name-like text between brackets: letters/digits/
# underscores with at least one letter — catalog names never contain
# spaces, so anything with a space, other characters, no letters (a
# "[1]" citation), or longer than the longest catalog name (+ slack)
# is ordinary prose and passes through to TTS untouched.
_TAG_MAX_LEN = 40
_TAG_LIKE = re.compile(r"^(?=.*[A-Za-z])[A-Za-z0-9_]+$")


class InlineGestureParser:
    """Incremental filter for streamed LLM text.

    Feed it text deltas; it returns the text with gesture tags removed,
    firing `on_gesture(name)` the moment a `[AnimationName]` tag
    completes — tags may arrive split across any number of deltas.
    Name-like tags that don't resolve are stripped, recorded in
    `misses`, and reported as `gesture_tag_unresolved` experiment
    events; non-name brackets pass through as prose. Call `flush()`
    after the stream ends to release a dangling '['.
    """

    def __init__(self, on_gesture):
        self._on_gesture = on_gesture
        self._buf: str | None = None  # None = passthrough; str = inside '[...'
        self.fired: list[str] = []
        self.misses: list[tuple[str, list[str]]] = []

    def feed(self, delta: str) -> str:
        out = []
        for ch in delta:
            if self._buf is None:
                if ch == "[":
                    self._buf = ""
                else:
                    out.append(ch)
            elif ch == "]":
                out.append(self._close_tag())
            elif ch == "[":
                # New '[' inside a candidate: what we buffered was prose.
                out.append("[" + self._buf)
                self._buf = ""
            else:
                self._buf += ch
                if len(self._buf) > _TAG_MAX_LEN or ch == "\n":
                    out.append("[" + self._buf)
                    self._buf = None
        return "".join(out)

    def _close_tag(self) -> str:
        candidate, self._buf = self._buf, None
        name, suggestions = resolve_gesture(candidate)
        if name is not None:
            self.fired.append(name)
            self._on_gesture(name)
            return ""
        if _TAG_LIKE.match(candidate or ""):
            print(f"[gest] unresolved tag [{candidate}] closest={suggestions}")
            emit_experiment_event("gesture_tag_unresolved", {
                "tag": candidate,
                "closest": suggestions,
            })
            self.misses.append((candidate, suggestions))
            return ""
        return f"[{candidate}]"

    def flush(self) -> str:
        """End of stream: return any buffered text that never closed."""
        if self._buf is None:
            return ""
        out = "[" + self._buf
        self._buf = None
        return out
